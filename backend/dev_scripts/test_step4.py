import os
import time
import httpx

BASE_URL = "http://localhost:8000"
NOTEBOOK_PRIMARY = "notebook_rag_101"
NOTEBOOK_SECONDARY = "notebook_rag_202"


def create_test_files():
    """Generate documents for RAG testing."""
    os.makedirs("test_files_step4", exist_ok=True)

    # Primary Notebook Document 1 (Solar Energy)
    doc1_path = "test_files_step4/solar_energy.txt"
    with open(doc1_path, "w", encoding="utf-8") as f:
        f.write(
            "Solar Energy Systems and Photovoltaic Performance\n\n"
            "Photovoltaic (PV) solar panels convert sunlight into direct current (DC) electricity using semiconductor materials like silicon. "
            "Modern monocrystalline solar panels achieve energy conversion efficiencies between 20% and 23%. "
            "Inverters convert DC electricity generated by PV modules into alternating current (AC) electricity suitable for grid distribution."
        )

    # Primary Notebook Document 2 (Battery Storage)
    doc2_path = "test_files_step4/battery_storage.txt"
    with open(doc2_path, "w", encoding="utf-8") as f:
        f.write(
            "Energy Storage Systems and Lithium-Ion Batteries\n\n"
            "Lithium-ion batteries are widely used for energy storage in solar power setups due to their high energy density and long cycle life. "
            "Battery Management Systems (BMS) monitor cell voltage, temperature, and state of charge to prevent thermal runaway."
        )

    # Secondary Notebook Document (Quantum Computing)
    doc3_path = "test_files_step4/quantum_computing.txt"
    with open(doc3_path, "w", encoding="utf-8") as f:
        f.write(
            "Quantum Computing Principles\n\n"
            "Quantum computers utilize quantum bits or qubits that exist in superpositions of states |0⟩ and |1⟩. "
            "Quantum entanglement allows qubits to share information instantaneously across quantum states."
        )

    return doc1_path, doc2_path, doc3_path


def run_tests():
    print("=== Starting Step 4: RAG + Gemini AI Chat End-to-End Test ===")
    doc1, doc2, doc3 = create_test_files()
    client = httpx.Client(base_url=BASE_URL, timeout=20.0)

    # 1. Upload files to Primary Notebook
    for doc_path in (doc1, doc2):
        with open(doc_path, "rb") as f:
            res = client.post(
                f"/api/v1/notebooks/{NOTEBOOK_PRIMARY}/sources/upload",
                files={"file": (os.path.basename(doc_path), f.read())},
            )
            assert res.status_code == 202
            print(f"Uploaded '{doc_path}' to {NOTEBOOK_PRIMARY}")

    # 2. Upload file to Secondary Notebook
    with open(doc3, "rb") as f:
        res = client.post(
            f"/api/v1/notebooks/{NOTEBOOK_SECONDARY}/sources/upload",
            files={"file": (os.path.basename(doc3), f.read())},
        )
        assert res.status_code == 202
        print(f"Uploaded '{doc3}' to {NOTEBOOK_SECONDARY}")

    print("Waiting 3 seconds for background document processing & vector embedding generation...")
    time.sleep(3)

    # Test 1: Simple Factual Question
    q1 = "What efficiency do monocrystalline solar panels achieve?"
    print(f"\n1. Test Factual Query on {NOTEBOOK_PRIMARY}: '{q1}'")
    res1 = client.post(f"/api/v1/notebooks/{NOTEBOOK_PRIMARY}/chat", json={"message": q1})
    assert res1.status_code == 200, f"Chat failed: {res1.text}"
    data1 = res1.json()
    conv_id = data1["conversation_id"]
    print(f"  -> Answer: {data1['answer']}")
    print(f"  -> Citations ({len(data1['citations'])}): {[c['source_name'] for c in data1['citations']]}")
    assert "20%" in data1["answer"] or "23%" in data1["answer"] or "solar" in data1["answer"].lower()
    assert len(data1["citations"]) > 0

    # Test 2: Question Spanning Multiple Documents (Solar + Battery)
    q2 = "How do solar panels and lithium-ion batteries work together?"
    print(f"\n2. Test Multi-Source Query on {NOTEBOOK_PRIMARY}: '{q2}'")
    res2 = client.post(f"/api/v1/notebooks/{NOTEBOOK_PRIMARY}/chat", json={"message": q2, "conversation_id": conv_id})
    assert res2.status_code == 200
    data2 = res2.json()
    print(f"  -> Answer: {data2['answer']}")
    print(f"  -> Sources Used ({len(data2['sources_used'])}): {data2['sources_used']}")
    assert len(data2["sources_used"]) >= 1

    # Test 3: Question NOT present in document (Zero Hallucination Test)
    q3 = "What is the secret recipe for baking sourdough bread?"
    print(f"\n3. Test Unsupported Query (Absent in documents): '{q3}'")
    res3 = client.post(f"/api/v1/notebooks/{NOTEBOOK_PRIMARY}/chat", json={"message": q3, "conversation_id": conv_id})
    assert res3.status_code == 200
    data3 = res3.json()
    print(f"  -> Answer: {data3['answer']}")
    print(f"  -> Citations count: {len(data3['citations'])}")
    assert "couldn't find enough information" in data3["answer"].lower() or len(data3["citations"]) == 0
    print("Verified zero-hallucination fallback response.")

    # Test 4: Follow-up Question Continuity
    q4 = "Can you summarize what we discussed so far?"
    print(f"\n4. Test Follow-up Question: '{q4}'")
    res4 = client.post(f"/api/v1/notebooks/{NOTEBOOK_PRIMARY}/chat", json={"message": q4, "conversation_id": conv_id})
    assert res4.status_code == 200
    print(f"  -> Answer: {res4.json()['answer']}")

    # Test 5: Strict Notebook Isolation
    print(f"\n5. Test Notebook Isolation ({NOTEBOOK_PRIMARY} vs {NOTEBOOK_SECONDARY})")
    q_quantum = "Explain qubits and quantum entanglement."
    res_iso = client.post(f"/api/v1/notebooks/{NOTEBOOK_PRIMARY}/chat", json={"message": q_quantum})
    assert res_iso.status_code == 200
    data_iso = res_iso.json()
    for c in data_iso["citations"]:
        assert c["source_name"] != "quantum_computing.txt", f"Cross-notebook leak! Found {c['source_name']} in {NOTEBOOK_PRIMARY}"
    print(f"Verified {NOTEBOOK_PRIMARY} cannot access quantum computing sources from {NOTEBOOK_SECONDARY}!")

    print("\n✅ ALL STEP 4 RAG & GEMINI CHAT TESTS PASSED SUCCESSFULLY!")


if __name__ == "__main__":
    run_tests()
